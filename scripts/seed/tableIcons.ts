// content/table-icons.json (docs/SPEC_V4.md §4.E, K-45): the 100 table icons in 20 themes, checked,
// seeded into public.table_icons (the server picks and checks from it) and written as the pure
// module the app and the functions read: supabase/functions/_shared/pure/tableIcons.ts.
// The app's images (step 4.5b): v46's 256 px WebP files copied to apps/mobile/assets/table-icons/
// and a module of static requires (Metro bundles only those) beside the list.
// tableIcons.test.ts checks the committed modules and files are the ones built from the content as
// it is now.
import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync } from 'node:fs';
import { resolve } from 'node:path';

import { format, resolveConfig } from 'prettier';

import { sqlLiteral } from './sql.ts';

export const TABLE_ICONS_MODULE = 'supabase/functions/_shared/pure/tableIcons.ts';
export const TABLE_ICON_IMAGES_MODULE = 'apps/mobile/src/features/rooms/tableIconImages.ts';
export const TABLE_ICON_SOURCE_DIR = 'docs/design/kaynak/masa-simgeleri/webp-256';
// skall's own pictures in the aura look (scripts/art/build.ts; the owner's call, 29 Ekim): an icon
// drawn anew here replaces v46's of the same id.
export const TABLE_ICON_AURA_DIR = 'docs/design/aura/masa-simgeleri';
export const TABLE_ICON_ASSET_DIR = 'apps/mobile/assets/table-icons';

export type TableIcon = { id: string; name: string; theme: string };
export type TableIconsContent = { themes: string[]; icons: TableIcon[] };

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

function text(value: unknown, field: string): string {
  if (typeof value !== 'string' || value.trim() === '') {
    throw new Error(`${field} must be a non-empty string`);
  }
  return value;
}

export function parseTableIcons(json: unknown): TableIconsContent {
  if (!isRecord(json) || !Array.isArray(json.themes) || !Array.isArray(json.icons)) {
    throw new Error('table-icons.json must have themes and icons');
  }
  const themes = json.themes.map((t, i) => text(t, `themes[${i}]`));
  const seen = new Set<string>();
  const icons = json.icons.map((icon, i) => {
    if (!isRecord(icon)) throw new Error(`icons[${i}] must be an object`);
    const id = text(icon.id, `icons[${i}].id`);
    // The icon's stored id (rooms.icon) and its file name in the app.
    if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(id)) throw new Error(`icons[${i}]: ${id} is not an id`);
    if (seen.has(id)) throw new Error(`icons: ${id} appears twice`);
    seen.add(id);
    const theme = text(icon.theme, `icons[${i}].theme`);
    if (!themes.includes(theme)) throw new Error(`icons[${i}]: no theme ${theme}`);
    return { id, name: text(icon.name, `icons[${i}].name`), theme };
  });
  if (icons.length === 0) throw new Error('table-icons.json has no icons');
  return { themes, icons };
}

// Upserted by id; an icon left out of the JSON stays for the tables that show it but is no longer
// given (is_active = false), like a card taken out of a deck.
export function tableIconsSql({ themes, icons }: TableIconsContent): string {
  const rows = icons.map(
    (icon, i) =>
      `(${sqlLiteral(icon.id)}, ${sqlLiteral(icon.name)}, ${sqlLiteral(icon.theme)}, ${themes.indexOf(icon.theme)}, ${i}, true)`,
  );
  return [
    '-- content/table-icons.json',
    'insert into public.table_icons (id, name, theme, theme_order, sort_order, is_active) values',
    `  ${rows.join(',\n  ')}`,
    'on conflict (id) do update set',
    '  name = excluded.name, theme = excluded.theme, theme_order = excluded.theme_order,',
    '  sort_order = excluded.sort_order, is_active = true;',
    `update public.table_icons set is_active = false where is_active and id <> all (${sqlLiteral(icons.map((i) => i.id))});`,
    '',
  ].join('\n');
}

export async function buildTableIconsModule(root: string): Promise<string> {
  const content = parseTableIcons(
    JSON.parse(readFileSync(resolve(root, 'content/table-icons.json'), 'utf8')),
  );
  const source = [
    '// Generated by `pnpm seed` (scripts/seed/tableIcons.ts) from content/table-icons.json. Do not',
    '// edit by hand.',
    '',
    `export const TABLE_ICON_THEMES = ${JSON.stringify(content.themes)};`,
    '',
    `export const TABLE_ICONS = ${JSON.stringify(content.icons)};`,
    '',
  ].join('\n');
  const options = await resolveConfig(resolve(root, TABLE_ICONS_MODULE));
  return format(source, { ...options, filepath: resolve(root, TABLE_ICONS_MODULE) });
}

// Each icon's image, by id: `require` paths relative to the module.
export async function buildTableIconImagesModule(root: string): Promise<string> {
  const { icons } = parseTableIcons(
    JSON.parse(readFileSync(resolve(root, 'content/table-icons.json'), 'utf8')),
  );
  const source = [
    '// Generated by `pnpm seed` (scripts/seed/tableIcons.ts) from content/table-icons.json and',
    "// v46's WebP files (docs/design/kaynak/masa-simgeleri/webp-256; the aura ones of",
    '// docs/design/aura/masa-simgeleri in their place). Do not edit by hand.',
    "import type { ImageSourcePropType } from 'react-native';",
    '',
    'export const TABLE_ICON_IMAGES: Record<string, ImageSourcePropType> = {',
    ...icons.map((i) => `  '${i.id}': require('../../../assets/table-icons/${i.id}.webp'),`),
    '};',
    '',
  ].join('\n');
  const options = await resolveConfig(resolve(root, TABLE_ICON_IMAGES_MODULE));
  return format(source, { ...options, filepath: resolve(root, TABLE_ICON_IMAGES_MODULE) });
}

// An icon's picture: the aura one when it has been drawn, else v46's.
export function tableIconSource(root: string, id: string): string {
  const aura = resolve(root, TABLE_ICON_AURA_DIR, `${id}.webp`);
  return existsSync(aura) ? aura : resolve(root, TABLE_ICON_SOURCE_DIR, `${id}.webp`);
}

// The listed icons' files, exactly: an icon left out of the JSON leaves the app too.
export function copyTableIconImages(root: string): void {
  const { icons } = parseTableIcons(
    JSON.parse(readFileSync(resolve(root, 'content/table-icons.json'), 'utf8')),
  );
  const target = resolve(root, TABLE_ICON_ASSET_DIR);
  rmSync(target, { recursive: true, force: true });
  mkdirSync(target, { recursive: true });
  for (const { id } of icons) {
    copyFileSync(tableIconSource(root, id), resolve(target, `${id}.webp`));
  }
}

export function tableIconAssetFiles(root: string): string[] {
  return readdirSync(resolve(root, TABLE_ICON_ASSET_DIR)).sort();
}
