// content/signum-words.json (docs/SPEC_V4.md Adım 4.6.7; the owner's decisions of 5 Kasım 2026):
// Signum's word pool. Seeded into public.cards as deck 'signum' (source_key and word the word;
// theme, prompt and forbidden empty). Each word is one word of letters, at least 3 of them, written
// as the server uses it (plainText(word).trim() === word: pickWords skips any other card), not
// twice, not on the profanity list, and at least SIGNUM.minPool of them.
//
// A word must also fit a tile: SIGNUM.tileTextPx at the tile's type (TILE_FONT). The widths come
// from the font itself: `pnpm seed` writes SIGNUM_WIDTHS_MODULE from the font file and the test
// measures every word with it (signum.test.ts), so the table is never written by hand.
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';

import { format, resolveConfig } from 'prettier';

import {
  containsProfanity,
  prepareTerms,
} from '../../supabase/functions/_shared/pure/profanity.ts';
import { isBoardWord, SIGNUM } from '../../supabase/functions/_shared/pure/signum.ts';
import { plainText } from '../../supabase/functions/_shared/pure/trText.ts';
import type { ProfanityList } from './content.ts';
import { type FontMetrics, readFontMetrics } from './fontMetrics.ts';

export const SIGNUM_WORDS = 'content/signum-words.json';
export const SIGNUM_WIDTHS_MODULE = 'scripts/seed/signumWidths.generated.ts';

// The tile's word: Plus Jakarta Sans 800, 12 px, letter spacing 2% of the size.
export const TILE_FONT = {
  file: 'node_modules/@expo-google-fonts/plus-jakarta-sans/800ExtraBold/PlusJakartaSans_800ExtraBold.ttf',
  sizePx: 12,
  letterSpacing: 0.02,
} as const;

// The letters the table measures: the Turkish alphabet and q, w, x, in both cases.
const LOWER = 'abcçdefgğhıijklmnoöpqrsştuüvwxyz';
export const MEASURED_CHARS = [...LOWER, ...LOWER.toLocaleUpperCase('tr-TR')].filter(
  (c, i, all) => all.indexOf(c) === i,
);

export function parseSignumWords(json: unknown, profanity: ProfanityList): string[] {
  if (
    typeof json !== 'object' ||
    json === null ||
    !Array.isArray((json as { words?: unknown }).words)
  ) {
    throw new Error('signum-words.json needs words');
  }
  const terms = prepareTerms(profanity.terms, profanity.wholeWords);
  const seen = new Set<string>();
  const words = (json as { words: unknown[] }).words.map((word, i) => {
    const at = `signum words[${i}]`;
    if (typeof word !== 'string') throw new Error(`${at} must be a string`);
    if (plainText(word).trim() !== word) throw new Error(`${at}: "${word}" is not written plainly`);
    if (!isBoardWord(word)) {
      throw new Error(
        `${at}: "${word}" must be one word of at least ${SIGNUM.minWordLength} letters`,
      );
    }
    const key = word.toLocaleLowerCase('tr-TR');
    if (seen.has(key)) throw new Error(`${at}: "${word}" twice`);
    if (containsProfanity(word, terms))
      throw new Error(`${at}: "${word}" is on the profanity list`);
    seen.add(key);
    return word;
  });
  if (words.length < SIGNUM.minPool) {
    throw new Error(`signum-words.json: ${words.length} words, at least ${SIGNUM.minPool}`);
  }
  return words;
}

// The width of `word` on a tile, in px: advances and kerning at TILE_FONT.sizePx, plus the letter
// spacing after each letter (as Android and the browser lay it out).
export function tileTextWidth(word: string, metrics: FontMetrics): number {
  const chars = [...word];
  let units = 0;
  chars.forEach((c, i) => {
    const advance = metrics.advance[c];
    if (advance === undefined) throw new Error(`"${c}" (in "${word}") is not in the width table`);
    units += advance;
    const previous = chars[i - 1];
    if (previous !== undefined) units += metrics.kern[previous + c] ?? 0;
  });
  const px = TILE_FONT.sizePx;
  return (units / metrics.unitsPerEm) * px + chars.length * TILE_FONT.letterSpacing * px;
}

export async function buildSignumWidthsModule(root: string): Promise<string> {
  const metrics = readFontMetrics(resolve(root, TILE_FONT.file), MEASURED_CHARS);
  const source = [
    '// Generated by `pnpm seed` (scripts/seed/signum.ts) from the font of the Signum tile',
    `// (${TILE_FONT.file.split('/').pop() ?? ''}). Do not edit by hand.`,
    "import type { FontMetrics } from './fontMetrics.ts';",
    '',
    `export const SIGNUM_TILE_METRICS: FontMetrics = ${JSON.stringify(metrics)};`,
    '',
  ].join('\n');
  const path = resolve(root, SIGNUM_WIDTHS_MODULE);
  const options = await resolveConfig(path);
  return format(source, { ...options, filepath: path });
}

export function readSignumWords(root: string, profanity: ProfanityList): string[] {
  return parseSignumWords(JSON.parse(readFileSync(resolve(root, SIGNUM_WORDS), 'utf8')), profanity);
}
